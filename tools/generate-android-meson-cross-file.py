#!/usr/bin/env python3
"""Generate a Meson cross file for Android NDK builds of upstream XWayland.

This only prepares toolchain configuration. It does not build dependencies or
claim that XWayland can yet link against the supplied target staging prefix.
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import shutil
import sys
from pathlib import Path

ABIS = {
    "armeabi-v7a": {
        "family": "arm",
        "cpu": "armv7a",
        "triplet": "arm-linux-androideabi",
        "compiler": "armv7a-linux-androideabi{api}-clang",
    },
    "arm64-v8a": {
        "family": "aarch64",
        "cpu": "aarch64",
        "triplet": "aarch64-linux-android",
        "compiler": "aarch64-linux-android{api}-clang",
    },
    "x86": {
        "family": "x86",
        "cpu": "i686",
        "triplet": "i686-linux-android",
        "compiler": "i686-linux-android{api}-clang",
    },
    "x86_64": {
        "family": "x86_64",
        "cpu": "x86_64",
        "triplet": "x86_64-linux-android",
        "compiler": "x86_64-linux-android{api}-clang",
    },
}


def meson_string(value: str) -> str:
    return json.dumps(value)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--abi", required=True, choices=sorted(ABIS))
    parser.add_argument("--api", type=int, default=24, help="Android API level (default: 24)")
    parser.add_argument("--ndk", default=os.environ.get("ANDROID_NDK_HOME") or os.environ.get("ANDROID_NDK_ROOT"))
    parser.add_argument("--prefix", required=True, help="Target-ABI dependency staging prefix")
    parser.add_argument("--output", required=True, help="Output Meson cross-file path")
    args = parser.parse_args()

    if args.api < 21 or args.api > 100:
        parser.error("--api must be between 21 and 100 for this NDK cross-file generator")
    if not args.ndk:
        parser.error("--ndk is required (or set ANDROID_NDK_HOME)")
    ndk = Path(args.ndk).expanduser().resolve()
    prefix = Path(args.prefix).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    toolchain_bin = ndk / "toolchains" / "llvm" / "prebuilt"
    candidates = sorted(toolchain_bin.glob("*/bin"))
    if not candidates:
        parser.error(f"NDK LLVM toolchain bin directory not found under {toolchain_bin}")
    # NDK packages normally contain one host-prebuilt directory. If multiple are
    # present, prefer the host whose executables exist instead of guessing.
    bins = [p for p in candidates if (p / "llvm-ar").is_file()]
    if len(bins) != 1:
        parser.error(f"expected exactly one usable NDK toolchain bin directory; found {len(bins)}")
    bin_dir = bins[0]
    sysroot = bin_dir.parent / "sysroot"
    if not sysroot.is_dir():
        parser.error(f"NDK sysroot not found: {sysroot}")

    spec = ABIS[args.abi]
    cc = bin_dir / spec["compiler"].format(api=args.api)
    cxx = bin_dir / spec["compiler"].format(api=args.api).replace("-clang", "-clang++")
    ar = bin_dir / "llvm-ar"
    strip = bin_dir / "llvm-strip"
    for tool in (cc, cxx, ar, strip):
        if not tool.is_file():
            parser.error(f"required NDK tool not found: {tool}")
    if not prefix.is_dir():
        parser.error(f"target dependency staging prefix does not exist: {prefix}")

    libdirs = [prefix / "lib" / "pkgconfig", prefix / "share" / "pkgconfig"]
    libdirs = [p for p in libdirs if p.is_dir()]
    if not libdirs:
        parser.error(f"no target pkg-config metadata found under {prefix}/lib or {prefix}/share")

    pkg_config = shutil.which("pkg-config")
    if not pkg_config:
        parser.error("pkg-config is required on the build host to generate the wrapper")

    output.parent.mkdir(parents=True, exist_ok=True)
    wrapper = output.with_name("android-pkg-config")
    wrapper.write_text(
        "#!/usr/bin/env bash\nset -Eeuo pipefail\n"
        "unset PKG_CONFIG_PATH PKG_CONFIG_SYSROOT_DIR\n"
        f"export PKG_CONFIG_LIBDIR={shlex.quote(os.pathsep.join(map(str, libdirs)))}\n"
        f"exec {shlex.quote(pkg_config)} \"$@\"\n",
        encoding="utf-8",
    )
    wrapper.chmod(0o755)

    c_args = [f"-I{prefix / 'include'}"]
    link_args = [f"-L{prefix / 'lib'}"]
    content = f"""# Generated by tools/generate-android-meson-cross-file.py.
# Review the staging prefix: all dependencies must be built for {args.abi}.
[binaries]
c = {meson_string(str(cc))}
cpp = {meson_string(str(cxx))}
ar = {meson_string(str(ar))}
strip = {meson_string(str(strip))}
pkg-config = {meson_string(str(wrapper))}

[host_machine]
system = 'android'
cpu_family = {meson_string(spec['family'])}
cpu = {meson_string(spec['cpu'])}
endian = 'little'

[properties]
sys_root = {meson_string(str(sysroot))}
pkg_config_libdir = {json.dumps(list(map(str, libdirs)))}
needs_exe_wrapper = true

[built-in options]
c_args = {json.dumps(c_args)}
cpp_args = {json.dumps(c_args)}
c_link_args = {json.dumps(link_args)}
cpp_link_args = {json.dumps(link_args)}
"""
    output.write_text(content, encoding="utf-8")
    print(f"Generated Meson cross file: {output}")
    print(f"Generated isolated pkg-config wrapper: {wrapper}")
    print(f"Target: {args.abi}, Android API {args.api}")
    print(f"Dependency staging prefix: {prefix}")
    print("NOTE: this configures the toolchain only; it does not build or validate XWayland dependencies.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
